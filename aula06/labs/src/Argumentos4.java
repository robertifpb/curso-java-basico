class Argumentos4 {
    public static void main(String[] args) {
        System.out.println("Quantidade de argumentos informados: " + args.length);
        for (int i = 0; i < args.length; i ++) {
            System.out.println("Argumento " + i + ":" +  args[i]);
        }
        System.out.println("Este Codigo utiliza Estrutura de Repeticao");
    }
}
